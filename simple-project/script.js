const html = document.documentElement;
const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".links");
const themeToggle = document.querySelector(".theme-toggle");
const languageButtons = document.querySelectorAll("[data-lang]");
const phaseTabs = document.getElementById("phase-tabs");
const phaseDetail = document.getElementById("phase-detail");
const conceptGraph = document.getElementById("concept-graph");
const conceptDetail = document.getElementById("concept-detail");
const trackSelect = document.getElementById("track");
const timeline = document.getElementById("timeline");
const form = document.getElementById("application-form");
const formMessage = document.getElementById("form-message");
const savedLanguage = localStorage.getItem("ai-language");
let language = savedLanguage === "en" ? "en" : "uk";
let activePhase = 0;
let activeConcept = "llm";
let submitted = false;

function t(key) {
  return translations[language][key];
}

function setTheme(theme) {
  html.dataset.theme = theme;
  themeToggle.textContent = t(theme === "dark" ? "theme.light" : "theme.dark");
  document.querySelector('meta[name="theme-color"]').setAttribute("content", theme === "dark" ? "#000000" : "#f8fff3");
  localStorage.setItem("ai-theme", theme);
}

function closeMenu() {
  navigation.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}

function renderPhase(index) {
  activePhase = index;
  const phases = content[language].phases;
  phaseTabs.innerHTML = phases.map((phase, itemIndex) => `
    <button class="phase-tab ${index === itemIndex ? "active" : ""}" type="button"
      role="tab" data-phase="${itemIndex}" aria-selected="${index === itemIndex}">
      <span>${phase[0]}</span><strong>${phase[2]}</strong><small>${phase[1]}</small>
    </button>`).join("");
  const phase = phases[index];
  phaseDetail.innerHTML = `
    <p class="tag">${phase[1]}</p>
    <h3>${phase[2]}</h3>
    <div class="module-tags">${phase[3].map((module) => `<span>${module}</span>`).join("")}</div>
    <p>${phase[4]}</p>
    <div class="outcome"><span>${t("program.outcome")}</span><strong>${phase[5]}</strong></div>`;
}

function renderConcept(key) {
  activeConcept = key;
  const concept = content[language].concepts[key];
  conceptDetail.innerHTML = `
    <p class="tag">${concept[1]}</p>
    <h3>${concept[0]}</h3>
    <p>${concept[2]}</p>
    <div class="concept-links"><span>${t("knowledge.related")}</span>
      ${concept[3].map((link) => `<strong>${link}</strong>`).join("")}
    </div>`;
  conceptGraph.querySelectorAll("[data-concept]").forEach((node) => {
    const selected = node.dataset.concept === key;
    node.classList.toggle("selected", selected);
    node.setAttribute("aria-pressed", String(selected));
  });
}

function renderTrack(key) {
  const track = content[language].tracks[key];
  timeline.innerHTML = `
    ${track[0].map((step, index) => `<div class="timeline-step"><span>0${index + 1}</span><strong>${step}</strong></div>`).join("")}
    <div class="destination">${t("roadmap.destination")}<strong>${track[1]}</strong></div>`;
}

function setLanguage(nextLanguage) {
  language = nextLanguage;
  html.lang = nextLanguage;
  localStorage.setItem("ai-language", nextLanguage);
  document.title = t("meta.title");
  document.getElementById("course-schema").textContent = JSON.stringify({
    "@context": "https://schema.org",
    "@type": "Course",
    name: "AI Engineer",
    description: t("meta.description"),
    provider: { "@type": "Organization", name: "AI Engineer Academy" },
    inLanguage: nextLanguage,
  });
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute("content", t(element.dataset.i18nContent));
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", t(element.dataset.i18nAlt));
  });
  languageButtons.forEach((button) => {
    const selected = button.dataset.lang === nextLanguage;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  setTheme(html.dataset.theme || "light");
  renderPhase(activePhase);
  renderConcept(activeConcept);
  renderTrack(trackSelect.value);
  if (submitted) formMessage.textContent = t("form.success");
}

menuToggle.addEventListener("click", () => {
  const open = navigation.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
document.querySelectorAll("[data-close-menu]").forEach((link) => link.addEventListener("click", closeMenu));
themeToggle.addEventListener("click", () => setTheme(html.dataset.theme === "dark" ? "light" : "dark"));
languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));
phaseTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-phase]");
  if (button) renderPhase(Number(button.dataset.phase));
});
conceptGraph.addEventListener("click", (event) => {
  const button = event.target.closest("[data-concept]");
  if (button) renderConcept(button.dataset.concept);
});
trackSelect.addEventListener("change", (event) => renderTrack(event.target.value));
form.addEventListener("submit", (event) => {
  event.preventDefault();
  if (form.checkValidity()) {
    form.reset();
    submitted = true;
    formMessage.textContent = t("form.success");
    formMessage.classList.add("success");
  }
});

setTheme(localStorage.getItem("ai-theme") || "light");
setLanguage(language);
